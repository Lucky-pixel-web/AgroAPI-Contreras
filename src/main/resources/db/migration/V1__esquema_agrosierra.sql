
CREATE TABLE ROL (
                     ID NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                     CODIGO VARCHAR2(50) NOT NULL,
                     CONSTRAINT PK_ROL PRIMARY KEY (ID),
                     CONSTRAINT UQ_ROL_CODIGO UNIQUE (CODIGO)
);

CREATE TABLE PRIVILEGIO (
                            ID NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                            CODIGO VARCHAR2(50) NOT NULL,
                            CONSTRAINT PK_PRIVILEGIO PRIMARY KEY (ID),
                            CONSTRAINT UQ_PRIVILEGIO_CODIGO UNIQUE (CODIGO)
);

CREATE TABLE ROL_PRIVILEGIO (
                                ROL_ID NUMBER(19,0) NOT NULL,
                                PRIVILEGIO_ID NUMBER(19,0) NOT NULL,
                                CONSTRAINT PK_ROL_PRIVILEGIO
                                    PRIMARY KEY (ROL_ID, PRIVILEGIO_ID),
                                CONSTRAINT FK_RP_ROL
                                    FOREIGN KEY (ROL_ID) REFERENCES ROL(ID),
                                CONSTRAINT FK_RP_PRIVILEGIO
                                    FOREIGN KEY (PRIVILEGIO_ID) REFERENCES PRIVILEGIO(ID)
);

CREATE TABLE USUARIO (
                         ID NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                         USERNAME VARCHAR2(80) NOT NULL,
                         CLAVE_HASH VARCHAR2(100) NOT NULL,
                         NOMBRE VARCHAR2(150) NOT NULL,
                         ACTIVO NUMBER(10,0) DEFAULT 1 NOT NULL,
                         ROL_ID NUMBER(19,0) NOT NULL,
                         CONSTRAINT PK_USUARIO PRIMARY KEY (ID),
                         CONSTRAINT UQ_USUARIO_USERNAME UNIQUE (USERNAME),
                         CONSTRAINT FK_USUARIO_ROL
                             FOREIGN KEY (ROL_ID) REFERENCES ROL(ID)
);

CREATE TABLE LOTE (
                      ID NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                      CODIGO VARCHAR2(30) NOT NULL,
                      NOMBRE VARCHAR2(150) NOT NULL,
                      HECTAREAS BINARY_DOUBLE NOT NULL,
                      CULTIVO VARCHAR2(100) NOT NULL,
                      VALLE VARCHAR2(100) NOT NULL,
                      CAMPANIA_CERRADA NUMBER(10,0) DEFAULT 0 NOT NULL,
                      DOSIS_MAXIMA_POR_HECTAREA BINARY_DOUBLE NOT NULL,
                      CONSTRAINT PK_LOTE PRIMARY KEY (ID),
                      CONSTRAINT UQ_LOTE_CODIGO UNIQUE (CODIGO),
                      CONSTRAINT CK_LOTE_CERRADA
                          CHECK (CAMPANIA_CERRADA IN (0,1))
);

CREATE TABLE LABOR (
                       ID NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                       LOTE_ID NUMBER(19,0) NOT NULL,
                       TIPO VARCHAR2(20) NOT NULL,
                       FECHA DATE NOT NULL,
                       RESPONSABLE VARCHAR2(80) NOT NULL,
                       CANTIDAD BINARY_DOUBLE NOT NULL,
                       OBSERVACION VARCHAR2(500) NOT NULL,
                       REGISTRADA_EN TIMESTAMP(6) NOT NULL,
                       CONSTRAINT PK_LABOR PRIMARY KEY (ID),
                       CONSTRAINT FK_LABOR_LOTE
                           FOREIGN KEY (LOTE_ID) REFERENCES LOTE(ID),
                       CONSTRAINT CK_LABOR_TIPO
                           CHECK (TIPO IN ('RIEGO','FUMIGACION','COSECHA'))
);

CREATE INDEX IDX_LABOR_LOTE ON LABOR(LOTE_ID);
CREATE INDEX IDX_LOTE_VALLE ON LOTE(VALLE);
